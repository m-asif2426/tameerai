"""
TameerAI - Structured AI Response Schemas (Phase 03A)
Pydantic v2 models for structured, grounded engineering AI outputs.
Enforces that AI recommendations are explicitly distinguished from certified
professional engineering decisions.
"""

from enum import Enum
from typing import Any, Dict, List, Optional
from uuid import UUID
from pydantic import BaseModel, Field

from app.ai.contracts.provider import TokenUsage, FinishReason


# ---------------------------------------------------------------------------
# Mandatory Professional Engineering Disclaimers
# ---------------------------------------------------------------------------

ENGINEERING_DISCLAIMER_TEXT = (
    "DISCLAIMER: This output is an automated advisory draft generated by AI and does not "
    "constitute a certified, approved, or legally verified professional engineering decision. "
    "Final sign-off by a licensed professional engineer (PEC) is mandatory."
)


# ---------------------------------------------------------------------------
# Enums
# ---------------------------------------------------------------------------

class ConfidenceLevel(str, Enum):
    """Categorical confidence based on retrieval coverage and groundedness."""
    HIGH = "high"          # Directly supported by explicit retrieved text
    MEDIUM = "medium"      # Inferred from multiple related sections
    LOW = "low"            # Sparse evidence, extrapolation needed
    UNCERTAIN = "uncertain"  # Conflicting or missing evidence


class AnalysisType(str, Enum):
    """Matches TameerAI engineering analysis disciplines."""
    COMPLIANCE_AUDIT = "compliance_audit"
    CONTRACT_ANALYSIS = "contract_analysis"
    BOQ_COST = "boq_cost"
    ENGINEERING_REPORT = "engineering_report"
    GENERAL_CONSULTATION = "general_consultation"


class HumanReviewRequirement(str, Enum):
    """Human engineering in the loop governance."""
    MANDATORY = "mandatory"    # Regulatory discrepancies, safety issues, cost overruns
    RECOMMENDED = "recommended"  # Typical advisory recommendations
    OPTIONAL = "optional"      # Informational clarifications
    NONE = "none"              # General greetings / non-engineering


# ---------------------------------------------------------------------------
# Sub-schemas
# ---------------------------------------------------------------------------

class EvidenceExcerpt(BaseModel):
    """Exact verbatim excerpt from retrieved evidence supporting a claim."""
    chunk_id: Optional[str] = None
    source_code: str = Field(..., description="Short reference code (e.g. PBC-2021, LDA-2019, FIDIC-Red)")
    page_number: Optional[int] = Field(default=None, ge=1)
    clause_or_section: Optional[str] = None
    exact_text: str = Field(..., min_length=1)
    relevance_score: Optional[float] = Field(default=None, ge=0.0, le=1.0)


class SourceCitation(BaseModel):
    """Normalized citation pointing to a regulatory codex or project document."""
    source_type: str = Field(..., description="'regulatory' or 'project_document'")
    source_code: str = Field(..., description="Unique code (e.g. PBC-2021, PRJ-DOC-001)")
    title: str = Field(..., min_length=1)
    section_or_clause: Optional[str] = None
    page_number: Optional[int] = Field(default=None, ge=1)
    verified_against_retrieval: bool = Field(default=False)


class WarningCard(BaseModel):
    """Structured engineering discrepancy or deficit alert card."""
    title: str = Field(..., min_length=1)
    severity: str = Field(..., pattern="^(critical|warning|info)$")
    description: str = Field(..., min_length=1)
    recommendation: str = Field(..., min_length=1)
    code_reference: Optional[str] = None


class AIProviderMetadata(BaseModel):
    """Execution telemetry strictly omitting secrets."""
    provider: str = Field(...)
    model_identifier: str = Field(...)
    latency_ms: float = Field(default=0.0, ge=0.0)
    usage: TokenUsage = Field(default_factory=TokenUsage)
    finish_reason: FinishReason = Field(default=FinishReason.STOP)


# ---------------------------------------------------------------------------
# Root AI Response Schema
# ---------------------------------------------------------------------------

class AIResponse(BaseModel):
    """
    Standardized AI advisory response contract.
    Used across chat, compliance, contract, cost, and report modules.
    """
    answer: str = Field(..., min_length=1, description="Primary advisory response in English")
    answer_urdu: Optional[str] = Field(default=None, description="Urdu translation or native response")
    analysis_type: AnalysisType = Field(default=AnalysisType.GENERAL_CONSULTATION)
    confidence: ConfidenceLevel = Field(default=ConfidenceLevel.MEDIUM)
    human_review_required: HumanReviewRequirement = Field(default=HumanReviewRequirement.RECOMMENDED)
    
    # Grounding and Citations
    citations: List[SourceCitation] = Field(default_factory=list)
    evidence_excerpts: List[EvidenceExcerpt] = Field(default_factory=list)
    missing_evidence: Optional[str] = Field(
        default=None,
        description="Explicit description of required documents or clauses not found in retrieval"
    )
    
    # Engineering Safety Cards
    warning_cards: List[WarningCard] = Field(default_factory=list)
    
    # Mandatory Safety & Professional Disclaimer
    disclaimer: str = Field(
        default=ENGINEERING_DISCLAIMER_TEXT,
        description="Immutable advisory disclaimer; AI output is never certified"
    )
    is_certified_decision: bool = Field(
        default=False,
        frozen=True,
        description="Always False. Certified decisions require human PEC engineer sign-off."
    )
    
    # Telemetry
    metadata: Optional[AIProviderMetadata] = None

